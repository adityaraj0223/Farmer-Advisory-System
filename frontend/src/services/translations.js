// Fallback helper function to get translated text
export function getTranslation(lang, key) {
  const dictionary = translations[lang] || translations.English;
  if (dictionary && dictionary[key]) {
    return dictionary[key];
  }
  return translations.English[key] || key;
}

// Google Translate sync helper (passive fallback without intrusive cookie)
export function syncGoogleTranslate(langName) {
  try {
    const langMap = {
      English: 'en',
      Hindi: 'hi',
      Marathi: 'mr',
      Punjabi: 'pa',
      Gujarati: 'gu',
      Tamil: 'ta',
      Telugu: 'te',
      Bengali: 'bn'
    };
    const code = langMap[langName] || 'en';
    const select = document.querySelector('.goog-te-combo');
    if (select) {
      select.value = code;
      select.dispatchEvent(new Event('change'));
    }
  } catch (e) {
    // quiet fallback
  }
}
